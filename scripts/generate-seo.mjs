/**
 * Writes client/public/robots.txt and client/public/sitemap.xml from the
 * shared practice config.
 *
 * Generated rather than hand-written so the domain lives in exactly one place
 * (BRAND.siteUrl). Runs automatically as part of `npm run build`; run it on
 * its own with `npm run seo` after changing the domain.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRAND } from '../shared/practice.config.js';

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(REPO, 'client', 'public');

const site = BRAND.siteUrl.replace(/\/$/, '');
const isPlaceholder = /example\.com/.test(site);

/**
 * Public, indexable routes only.
 *
 * /book, /confirmation/* and /admin are deliberately absent: the first two are
 * transactional (a patient's own confirmation page has no business in a search
 * index) and the third is the clinic's. Seo.jsx also sends noindex on them, so
 * the two agree.
 */
const ROUTES = [
  { path: '/', priority: '1.0', changefreq: 'weekly' },
  { path: '/about', priority: '0.8', changefreq: 'monthly' },
  { path: '/services', priority: '0.8', changefreq: 'monthly' },
  { path: '/faq', priority: '0.7', changefreq: 'monthly' },
  { path: '/contact', priority: '0.6', changefreq: 'monthly' },
  { path: '/privacy', priority: '0.3', changefreq: 'yearly' },
  { path: '/terms', priority: '0.3', changefreq: 'yearly' },
  { path: '/refund', priority: '0.3', changefreq: 'yearly' },
];

const today = new Date().toISOString().slice(0, 10);

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${ROUTES.map(
  (r) => `  <url>
    <loc>${site}${r.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${r.changefreq}</changefreq>
    <priority>${r.priority}</priority>
  </url>`,
).join('\n')}
</urlset>
`;

const robots = `# Generated by scripts/generate-seo.mjs — do not edit by hand.
User-agent: *
Allow: /

# Transactional and private areas. A patient's own confirmation page should
# never be indexable, and the clinic view is behind a token regardless.
Disallow: /book
Disallow: /confirmation/
Disallow: /admin
Disallow: /account

Sitemap: ${site}/sitemap.xml
`;

fs.mkdirSync(PUBLIC, { recursive: true });
fs.writeFileSync(path.join(PUBLIC, 'sitemap.xml'), sitemap);
fs.writeFileSync(path.join(PUBLIC, 'robots.txt'), robots);

console.log(`  SEO files written for ${site}`);
console.log(`    client/public/sitemap.xml  (${ROUTES.length} routes)`);
console.log('    client/public/robots.txt');

if (isPlaceholder) {
  console.log(
    '\n  NOTE: BRAND.siteUrl is still the placeholder. Set the real domain in\n' +
      '        shared/practice.config.js and rebuild, or the sitemap will point\n' +
      '        search engines at example.com.\n',
  );
}
